"""Passive observation of the frozen paper runtime during an explicit single-process pilot."""

import asyncio
import hashlib
import logging
import os
import queue
import threading
import time
import uuid
from collections.abc import Callable, Iterator
from contextlib import ExitStack, contextmanager
from contextvars import ContextVar
from pathlib import Path
from typing import Any
from unittest.mock import patch

from kalshi_edge_engine.evidence import references
from tools.microstructure import journal

PROTOCOL = "b3b2-paper-proposals-v1"
ENROLLMENT = "enrollment.json"
EVENTS = "paper-events.jsonl"
SEAL = "link-seal.json"


class Sidecar:
    def __init__(self, directory: Path, enrollment: dict):
        self.file = (directory / EVENTS).open("xb")
        self.session = enrollment["paper_session"]
        self.origin = uuid.uuid4().hex
        self.count = 0
        self.failed = False
        self.pending: queue.Queue[bytes | None] = queue.Queue(maxsize=8192)
        self.writer = threading.Thread(target=self._drain, name="paper-evidence-writer")
        self.writer.start()

    def _drain(self) -> None:
        while (line := self.pending.get()) is not None:
            try:
                self.file.write(line)
                self.file.flush()
            except OSError:
                if not self.failed:
                    logging.getLogger(__name__).exception("Paper evidence file failed")
                self.failed = True

    def write(self, kind: str, **fields: Any) -> None:
        # Evidence failures invalidate the recording without changing an admission or draw.
        if self.failed:
            return
        try:
            row = dict(
                fields,
                kind=kind,
                n=self.count + 1,
                session=self.session,
                origin=self.origin,
                pid=os.getpid(),
                wall_ns=time.time_ns(),
                mono_ns=time.monotonic_ns(),
            )
            self.pending.put_nowait(journal.encoded(row))
            self.count += 1
        except (queue.Full, TypeError, ValueError):
            self.failed = True
            logging.getLogger(__name__).exception("Paper evidence sidecar failed")

    def close(self) -> None:
        self.pending.put(None)
        self.writer.join()
        try:
            self.file.flush()
            os.fsync(self.file.fileno())
        finally:
            self.file.close()


@contextmanager
def observe(
    sink: Sidecar,
    store: Any,
    recorder: Any,
    resolver: Any,
    markets: dict[str, str],
    *,
    track_scanner: bool = False,
    track_selectivity: bool = False,
) -> Iterator[None]:
    from kalshi_edge_engine.runtime import paper_runtime as runtime

    current: ContextVar[str | None] = ContextVar("paper_proposal", default=None)
    classified: ContextVar[bool] = ContextVar("classified_signal", default=False)
    build = runtime.build_quote_intents
    insert = store.insert_intent
    book_fill = store.insert_fill_result
    capture = recorder.capture
    gate = runtime._get_rate_limit_or_cooldown_reason
    observe_market = resolver.observe_entry_market
    paths = (
        {"/markets/" + m for m in markets}
        | {"/events/" + e for e in markets.values()}
        | {"/series/KXNBAGAME"}
    )

    def proposals(signal: Any) -> Iterator:
        intents = build(signal)
        decision_mono, decision_wall = time.monotonic_ns(), time.time_ns()
        classified.set(True)
        # Both sides are generated by one real builder call before either gate is evaluated.
        for intent in intents:
            details = {}
            if track_selectivity:
                cfg = runtime.runtime_config.get_effective_paper_config(intent.universe)
                details["side_enabled"] = (
                    cfg.allow_yes_entries if intent.side == "YES" else cfg.allow_no_entries
                )
            sink.write(
                "proposal",
                intent_id=intent.id,
                ticker=intent.ticker,
                side=intent.side.lower(),
                direction="buy",
                price_cents=str(intent.quote_price_cents),
                contracts=intent.size_contracts,
                universe=intent.universe,
                created_ts_ms=intent.created_ts_ms,
                decision_mono_ns=decision_mono,
                decision_wall_ns=decision_wall,
                signal_reason=signal.reason_code,
                scored_wall_ns=signal.scored_ns,
                source_receipts=references(signal.receipts),
                **details,
            )
        if not intents:
            sink.write("no_proposal", ticker=signal.ticker, reason=signal.reason_code)

        # Set attribution only while the strategy evaluates this particular proposal.
        def iterate() -> Iterator:
            for intent in intents:
                token = current.set(intent.id)
                try:
                    yield intent
                finally:
                    current.reset(token)

        return iterate()

    def insert_intent(intent: Any, **kwargs: Any) -> Any:
        result = insert(intent, **kwargs)
        sink.write(
            "admission",
            intent_id=intent.id,
            admitted=result,
            reason=None if result else "store_declined",
            submission=kwargs.get("submission_evidence"),
        )
        return result

    def rate_gate(ticker: str, now_ms: int) -> str | None:
        result = gate(ticker, now_ms)
        if result and current.get():
            sink.write("reject", intent_id=current.get(), reason=result)
        return result

    def insert_fill(**kwargs: Any) -> Any:
        result = book_fill(**kwargs)
        if result.inserted_new_fill:
            sink.write("paper_booking", intent_id=kwargs["intent_id"], fill_id=kwargs["fill_id"])
        return result

    async def market_observation(ticker: str) -> Any:
        result = await observe_market(ticker)
        # Simulator poll tasks inherit the context. Only the submission task is an admission.
        if result is None and current.get() and asyncio.current_task() is evaluating.get():
            sink.write("reject", intent_id=current.get(), reason="submission_market_unavailable")
        return result

    def get_receipt(
        path: str, lane: str, received_ns: int, data: dict, body: bytes, base_url: str
    ) -> Any:
        mono = time.monotonic_ns()
        ref = capture(path, lane, received_ns, data, body, base_url)
        if path in paths and ref is not None:
            sink.write(
                "fee_receipt",
                path=path,
                ref=references([ref])[0],
                base_url=base_url,
                receipt_mono_ns=mono,
                body_sha256=hashlib.sha256(body).hexdigest(),
            )
        return ref

    def observe_reason(original: Callable) -> Callable:
        # Read the gate's own reason even when application logging is disabled.
        def log(message: str, *args: Any, **kwargs: Any) -> None:
            fields = kwargs.get("extra", {})
            if message == "paper_intent_skipped":
                classified.set(True)
                sink.write(
                    "reject" if current.get() else "no_proposal",
                    intent_id=current.get(),
                    ticker=fields.get("ticker"),
                    reason=fields.get("reason"),
                )
            elif message == "paper_intent_store_error":
                sink.write("reject", intent_id=fields.get("intent_id"), reason="store_error")
            original(message, *args, **kwargs)

        return log

    from kalshi_edge_engine.runtime import scanner_runtime

    evaluating: ContextVar[Any] = ContextVar("paper_evaluating_task", default=None)
    process = scanner_runtime._process_paper_intents

    async def process_signal(signal: Any, client: Any) -> None:
        token = evaluating.set(asyncio.current_task())
        called = classified.set(False)
        try:
            await process(signal, client)
            if not classified.get():
                sink.write(
                    "no_proposal",
                    ticker=signal.ticker,
                    reason="fee_profile_unavailable"
                    if signal.fee_profile is None
                    else "paper_or_fee_gate",
                )
        finally:
            classified.reset(called)
            evaluating.reset(token)

    with ExitStack() as stack:
        if track_selectivity:
            count_open = store.count_intents_by_status

            def portfolio_check(status: str) -> Any:
                if current.get() and asyncio.current_task() is evaluating.get():
                    sink.write("entry_gates_passed", intent_id=current.get())
                return count_open(status)

            stack.enter_context(patch.object(store, "count_intents_by_status", portfolio_check))
        if track_scanner:
            score = scanner_runtime._score_market

            async def score_market(client: Any, ticker: str, universe: str) -> Any:
                if ticker not in markets:
                    return await score(client, ticker, universe)
                sink.write("scanner_visit", ticker=ticker)
                try:
                    signal = await score(client, ticker, universe)
                except Exception as exc:
                    sink.write("scanner_score_error", ticker=ticker, error_type=type(exc).__name__)
                    raise
                sink.write(
                    "scanner_score",
                    ticker=ticker,
                    reason=signal.reason_code,
                    scored_ns=signal.scored_ns,
                    source_receipts=references(signal.receipts),
                )
                return signal

            stack.enter_context(patch.object(scanner_runtime, "_score_market", score_market))
        for obj, name, wrapper in (
            (runtime.logger, "info", observe_reason(runtime.logger.info)),
            (runtime.logger, "exception", observe_reason(runtime.logger.exception)),
            (runtime, "build_quote_intents", proposals),
            (store, "insert_intent", insert_intent),
            (store, "insert_fill_result", insert_fill),
            (runtime, "_get_rate_limit_or_cooldown_reason", rate_gate),
            (resolver, "observe_entry_market", market_observation),
            (recorder, "capture", get_receipt),
            (scanner_runtime, "_process_paper_intents", process_signal),
        ):
            stack.enter_context(patch.object(obj, name, wrapper))
        yield
